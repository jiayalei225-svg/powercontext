def _content_blocks(paper: dict) -> list[tuple[str, str]]:
    blocks = [(paper["meta"][0][1], "title")]
    blocks += [(f"{key}：{value}", "meta") for key, value in paper["meta"][1:]]
    blocks.append((paper["abstract"], "body"))
    blocks.append((paper["keywords"], "note"))
    for heading, paragraphs in paper["body"]:
        blocks.append((heading, "heading"))
        blocks.extend((paragraph, "body") for paragraph in paragraphs)
    return blocks


def render(paper: dict, target: Path) -> None:
    doc = pymupdf.open()
    page = doc.new_page(width=PAGE_W, height=PAGE_H)
    cursor = {"y": MARGIN}

    def place(text: str, size: float = 10.5, gap: float = 9.0) -> None:
        nonlocal page
        while True:
            if cursor["y"] > PAGE_H - MARGIN - size * 2:
                page = doc.new_page(width=PAGE_W, height=PAGE_H)
                cursor["y"] = MARGIN
            rect = pymupdf.Rect(MARGIN, cursor["y"], PAGE_W - MARGIN, PAGE_H - MARGIN)
            remaining = page.insert_textbox(
                rect,
                text,
                fontsize=size,
                fontname="SimHei",
                fontfile=str(FONT),
                lineheight=1.55,
                align=0,
            )
            if remaining >= 0:
                cursor["y"] = PAGE_H - MARGIN - remaining + gap
                return
            page = doc.new_page(width=PAGE_W, height=PAGE_H)
            cursor["y"] = MARGIN

    styles = {
        "title": (18.0, 14.0),
        "meta": (9.5, 2.0),
        "note": (9.5, 8.0),
        "heading": (12.0, 6.0),
        "body": (10.5, 9.0),
    }
    for text, kind in _content_blocks(paper):
        size, gap = styles[kind]
        place(text, size=size, gap=gap)
    doc.save(target)
    doc.close()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for paper in PAPERS:
        target = OUT / paper["file"]
        render(paper, target)
        print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
